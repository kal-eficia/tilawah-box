"""What the box is doing: which surah, which ayah, playing or paused, how loud.

The Player holds the state and decides what to play. A backend makes sound:
MpvBackend on the Pi, DryRunBackend for tests and the simulator.
"""
from __future__ import annotations

import json
import os
import shutil
import socket
import subprocess
import tempfile
import time
from dataclasses import dataclass, field

from .quran import ayat, name
from .sources import RECITERS, Library


class DryRunBackend:
    """Records what would play. Used by the tests and `tilawah sim --silent`."""

    def __init__(self, echo=None):
        self.playlist: list[str] = []
        self.paused = False
        self.volume = 0
        self.log: list[str] = []
        self.echo = echo

    def _say(self, msg):
        self.log.append(msg)
        if self.echo:
            self.echo(msg)

    def play(self, playlist):
        self.playlist, self.paused = list(playlist), False
        self._say(f"play {len(playlist)} file(s) from {playlist[0] if playlist else ''}")

    def pause(self, paused: bool):
        self.paused = paused
        self._say("paused" if paused else "resumed")

    def set_volume(self, v: int):
        self.volume = v

    def stop(self):
        self.playlist = []
        self._say("stopped")

    def chime(self):
        self._say("chime")

    def finished(self) -> bool:
        return False


class MpvBackend:
    """Plays through mpv, controlled over its JSON IPC socket. Gapless between ayat."""

    def __init__(self):
        if not shutil.which("mpv"):
            raise RuntimeError("mpv is not installed: sudo apt install mpv")
        self.sock_path = os.path.join(tempfile.gettempdir(), "tilawah-mpv.sock")
        self.proc: subprocess.Popen | None = None
        self.volume = 60

    def _cmd(self, *args):
        for _ in range(20):
            try:
                with socket.socket(socket.AF_UNIX) as s:
                    s.connect(self.sock_path)
                    s.sendall((json.dumps({"command": list(args)}) + "\n").encode())
                    return
            except OSError:
                time.sleep(0.05)

    def play(self, playlist):
        self.stop()
        items = list(playlist)
        self.proc = subprocess.Popen(
            ["mpv", "--no-video", "--really-quiet", "--gapless-audio=yes", f"--volume={self.volume}",
             f"--input-ipc-server={self.sock_path}", *items],
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    def pause(self, paused: bool):
        self._cmd("set_property", "pause", paused)

    def set_volume(self, v: int):
        self.volume = v
        self._cmd("set_property", "volume", v)

    def stop(self):
        if self.proc and self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=2)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        self.proc = None

    def chime(self):
        # a soft two-tone sine chime, generated by mpv itself: no music, no files needed
        subprocess.Popen(["mpv", "--no-video", "--really-quiet", f"--volume={max(20, self.volume - 10)}",
                          "av://lavfi:sine=frequency=660:duration=0.12,afade=t=out:st=0.06:d=0.06"],
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    def finished(self) -> bool:
        return self.proc is not None and self.proc.poll() is not None


@dataclass
class Player:
    library: Library
    backend: object
    reciters: list[str] = field(default_factory=lambda: ["alafasy", "husary", "minshawi"])
    surah: int = 1
    reciter_index: int = 0
    volume: int = 60
    max_volume: int = 85
    playing: bool = False
    paused: bool = False
    hifz_repeat: int = 1          # play each ayah this many times (memorisation mode)
    range_: tuple[int, int] | None = None  # (from ayah, to ayah) within the surah

    def __post_init__(self):
        for r in self.reciters:
            if r not in RECITERS:
                raise ValueError(f"unknown reciter {r!r}: choose from {', '.join(RECITERS)}")
        self.backend.set_volume(self.volume)

    @property
    def reciter(self) -> str:
        return self.reciters[self.reciter_index]

    def describe(self) -> str:
        span = f" ayat {self.range_[0]}-{self.range_[1]}" if self.range_ else ""
        hifz = f", each ayah x{self.hifz_repeat}" if self.hifz_repeat > 1 else ""
        state = "paused" if self.paused else ("playing" if self.playing else "stopped")
        return f"{self.surah}. {name(self.surah)}{span} · {RECITERS[self.reciter][1]}{hifz} · vol {self.volume} · {state}"

    def _playlist(self) -> list[str]:
        start, end = self.range_ or (1, ayat(self.surah))
        items = []
        # Bismillah once before every surah except Al-Fatihah (where it is ayah 1) and At-Tawbah
        if start == 1 and self.surah not in (1, 9):
            items.append(self.library.source(self.reciter, 1, 1))
        for a in range(start, end + 1):
            items += [self.library.source(self.reciter, self.surah, a)] * self.hifz_repeat
        return items

    # ---- actions (each maps to a button, a dial turn, a card tap or a schedule)
    def play(self, surah: int | None = None, range_: tuple[int, int] | None = None):
        if surah is not None:
            self.surah = surah
            self.range_ = range_
        if self.range_:
            a, b = self.range_
            if not 1 <= a <= b <= ayat(self.surah):
                raise ValueError(f"{name(self.surah)} has {ayat(self.surah)} ayat")
        self.backend.play(self._playlist())
        self.playing, self.paused = True, False

    def toggle(self):
        if not self.playing:
            return self.play()
        self.paused = not self.paused
        self.backend.pause(self.paused)

    def stop(self):
        self.backend.stop()
        self.playing = self.paused = False

    def step_surah(self, delta: int):
        self.surah = (self.surah - 1 + delta) % 114 + 1
        self.range_ = None
        if self.playing:
            self.play()
        else:
            self.backend.chime()

    def next_reciter(self):
        self.reciter_index = (self.reciter_index + 1) % len(self.reciters)
        self.backend.chime()
        if self.playing:
            self.play()

    def change_volume(self, delta: int):
        self.volume = max(0, min(self.max_volume, self.volume + delta))
        self.backend.set_volume(self.volume)

    def cycle_hifz(self):
        self.hifz_repeat = {1: 3, 3: 5, 5: 10, 10: 1}.get(self.hifz_repeat, 1)
        self.backend.chime()
        if self.playing:
            self.play()
